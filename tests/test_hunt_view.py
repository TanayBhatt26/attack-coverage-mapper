class _ExpanderCM:
    """Minimal context manager mimicking ``st.expander()``'s return value."""

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return None


class _RenderHarness:
    """Capture the Streamlit calls a render produces.

    Each ``st.<widget>`` is replaced with a recording mock; we then replay
    the captured calls to assert the contract.  ``st.expander`` returns a
    context-manager-like mock whose ``__enter__``/``__exit__`` are no-ops so
    the view's ``with st.expander(...)`` body runs under capture.
    """

    def __init__(self) -> None:
        self.calls: dict[str, list[tuple[tuple, dict]]] = {}
        self._expander_stack: list[str] = []

    def _record(self, name: str):
        def _fn(*args, **kwargs):
            self.calls.setdefault(name, []).append((args, kwargs))
            # expander() must return a working context manager.  The
            # __enter__/__exit__ must live on the *type* for ``with`` to work,
            # so a plain SimpleNamespace instance attribute is not enough --
            # use a dedicated class.
            if name == "expander":
                label = args[0] if args else kwargs.get("label", "")
                self._expander_stack.append(label)
                return _ExpanderCM()
            if name == "code":
                return MagicMock()
            return MagicMock()

        return _fn

    def patchers(self):
        names = [
            "header", "caption", "subheader", "markdown", "code",
            "expander", "warning", "info", "success", "error",
            "spinner", "dataframe", "sidebar", "number_input",
            "radio", "set_page_config", "stop",
        ]
        return [patch.object(st, n, self._record(n)) for n in names]

    @contextlib.contextmanager
    def capture(self):
        """Enter all st.* patchers plus a spinner patch for a render."""
        with contextlib.ExitStack() as stack:
            for p in self.patchers():
                stack.enter_context(p)
            stack.enter_context(
                patch.object(st, "spinner", self._record("spinner"))
            )
            yield

    def expanders(self) -> list[str]:
        """Labels passed to ``st.expander(...)``, in call order."""
        return [args[0] for args, _ in self.calls.get("expander", [])]

    def codes(self) -> list[tuple[tuple, dict]]:
        """Args/kwargs passed to ``st.code(...)``."""
        return self.calls.get("code", [])

    def markdowns(self) -> list[str]:
        """All positional string args passed to ``st.markdown(...)``."""
        out: list[str] = []
        for args, _ in self.calls.get("markdown", []):
            if args and isinstance(args[0], str):
                out.append(args[0])
        return out

    def warnings(self) -> list[str]:
        """All positional string args passed to ``st.warning(...)``."""
        out: list[str] = []
        for args, _ in self.calls.get("warning", []):
            if args and isinstance(args[0], str):
                out.append(args[0])
        return out


