def _fake_queries(n: int, *, ordered: bool = True) -> OrderedDict:
    """Build a minimal ordered query dict of *n* missed techniques.

    Cycles through the three attribution labels so the view exercises every
    badge/attribution path.  ``ordered=True`` emits technique ids in ASC order
    (T1000..); ``ordered=False`` shuffles them to prove the view does not
    depend on input order for its own ordering (the pipeline already orders).
    """
    labels = ["hand-curated", "community-sourced", "generic"]
    records: OrderedDict[str, dict] = OrderedDict()
    ids = [f"T{i:04d}" for i in range(1, n + 1)]
    if not ordered:
        # Deterministic reverse so the test is reproducible.
        ids = list(reversed(ids))
    for i, tid in enumerate(ids):
        label = labels[i % len(labels)]
        rec: dict[str, Any] = {
            "query": f'source="x" technique="{tid}" | stats count',
            "query_language": "splunk",
            "attribution_label": label,
            "source_rule_id": None,
            "closable_by": ("evtx",),
            "confidence": 0.42,
            "attribution": {},
        }
        if label == "community-sourced":
            rec["attribution"] = {
                "title": f"Rule for {tid}",
                "author": "Sigma Author",
                "rule_uuid": "00000000-0000-4000-8000-000000000001",
                "rule_url": f"https://github.com/SigmaHQ/sigma/blob/master/rules/win_{tid}.yml",
                "rule_set_url": "https://github.com/SigmaHQ/sigma",
            }
            rec["source_rule_id"] = "00000000-0000-4000-8000-000000000001"
        elif label == "hand-curated":
            rec["attribution"] = {"author": "ATT&CK Coverage Mapper core set"}
            rec["source_rule_id"] = "M001"
        records[tid] = rec
    return records


