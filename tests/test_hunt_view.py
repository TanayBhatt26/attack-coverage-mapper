"""Contract tests for the Phase 6 Streamlit Hunt view.

Verifies the frozen dashboard contract (``research/p5-wave1-full-results.md``
agent-436) that :func:`src.visualization.views.hunt.render_hunt_view`
renders:

1. Gap list: one row per missed technique, ordered ``technique_attack_id ASC``;
   count MUST equal ``missed_count`` (work-list invariant).
2. Per-technique ``st.expander(f"{technique_attack_id} — {technique_name}")``.
3. Body: ``st.code(query, language=query_language)`` (built-in copy widget),
   colored source badge, attribution block.
4. Attribution block shape varies by ``attribution_label``:
   - community-sourced: title/author/rule_id/repo_url, DRL 1.1 license, statement.
   - hand-curated: author="ATT&CK Coverage Mapper", license="project-original".
   - generic: license="template — not a detection rule"; UNREVIEWED header.

Streamlit itself is mocked so these tests run offline in ``pytest -q`` with no
browser.  We assert the *render contract* (which widgets are called with what
arguments), not pixels.

These tests are idempotent and roll back all Phase-5 persistence via the
read-only SQLite fixture shared with the Phase-4/5 suites.
"""

