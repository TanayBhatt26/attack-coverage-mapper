class TestGapListInvariant:
    """One render row per missed technique, ordered ASC."""

    def test_expander_count_equals_missed_count(
        self, tmp_path: Path, repo_config: dict, harness: _RenderHarness
    ) -> None:
        engine, session = _attach_readonly_sqlite(tmp_path)
        try:
            result = (
                session.execute(select(SimulationResult))
                .scalars()
                .first()
            )
            assert result is not None

            with patch.object(hunt, "export_all_queries") as mock_export:
                mock_export.return_value = _fake_queries(result.missed_count)
                with harness.capture():
                    hunt.render_hunt_view(
                        result.id, session=session, config=repo_config
                    )
            session.rollback()

            expanders = harness.expanders()
            # Exactly one expander per missed technique.
            assert len(expanders) == result.missed_count
        finally:
            session.close()
            engine.dispose()

    def test_expanders_ordered_by_technique_id_asc(
        self, tmp_path: Path, repo_config: dict, harness: _RenderHarness
    ) -> None:
        engine, session = _attach_readonly_sqlite(tmp_path)
        try:
            result = (
                session.execute(select(SimulationResult))
                .scalars()
                .first()
            )
            with patch.object(hunt, "export_all_queries") as mock_export:
                mock_export.return_value = _fake_queries(
                    result.missed_count, ordered=True
                )
                with harness.capture():
                    hunt.render_hunt_view(
                        result.id, session=session, config=repo_config
                    )
            session.rollback()

            ids = [_expander_id(label) for label in harness.expanders()]
            assert ids == sorted(ids)
        finally:
            session.close()
            engine.dispose()

    def test_empty_missed_list_renders_info(
        self, tmp_path: Path, repo_config: dict, harness: _RenderHarness
    ) -> None:
        engine, session = _attach_readonly_sqlite(tmp_path)
        try:
            result = (
                session.execute(select(SimulationResult))
                .scalars()
                .first()
            )
            with patch.object(hunt, "export_all_queries") as mock_export:
                mock_export.return_value = OrderedDict()
                with harness.capture():
                    hunt.render_hunt_view(
                        result.id, session=session, config=repo_config
                    )
            # No expanders when there are no missed techniques.
            assert harness.expanders() == []
            # An info banner is shown instead.
            assert any(
                "no missed techniques" in m.lower() or "nothing to hunt" in m.lower()
                for m in _all_text(harness)
            )
        finally:
            session.close()
            engine.dispose()


