def _expander_id(label: str) -> str:
    """Extract the technique_attack_id from an expander label."""
    return label.split(" — ", 1)[0]


def _all_text(harness: _RenderHarness) -> list[str]:
    """All string fragments the view rendered (markdowns + warnings + info)."""
    out: list[str] = []
    out.extend(harness.markdowns())
    out.extend(harness.warnings())
    for args, _ in harness.calls.get("info", []):
        if args and isinstance(args[0], str):
            out.append(args[0])
    return out
