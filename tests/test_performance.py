"""Performance gates (Phase 7).

Verifies the normative performance gates from the blueprint §16:

- Full recompute (load coverage rows + by-tactic rollup + gap analysis + APT
  simulation) completes in under 5 seconds.
- Cached render path (the same pipeline but with a pre-computed session and
  config already in memory) completes in under 3 seconds.

The analysis pipeline is CPU-light on the committed dev DB (measured ~64 ms
total), so these gates are loose upper bounds against future dataset growth.
The test asserts the gates and fails loudly if a regression pushes either
budget over the limit.

Run: PYTHONPATH=src ./.venv/Scripts/python.exe -m pytest tests/test_performance.py -q
"""

from __future__ import annotations

import time
from pathlib import Path

import pytest
from sqlalchemy import select
from sqlalchemy.orm import sessionmaker

from src.analysis.coverage_analyzer import (
    calculate_coverage_gaps,
    coverage_by_tactic,
    load_coverage_rows,
)
from src.analysis.simulation import simulate_apt_attack
from src.config_loader import load_config
from src.database.models import SimulationResult
from src.database.session import database_url, make_engine
from src.parser.mappings_io import load_mappings

# Gate budgets (seconds) — per blueprint §16.
FULL_RECOMPUTE_BUDGET = 5.0
CACHED_RENDER_BUDGET = 3.0

# Skip all performance tests if the dev database doesn't have the required tables
# (it's a runtime artifact regenerated by the ingest scripts, not committed to git).
def _db_has_tables() -> bool:
    db_path = Path("db/coverage.db")
    if not db_path.exists():
        return False
    try:
        from src.database.session import make_engine
        from sqlalchemy import inspect
        engine = make_engine(f"sqlite:///{db_path}")
        try:
            tables = inspect(engine).get_table_names()
            return "simulation_results" in tables
        finally:
            engine.dispose()
    except Exception:
        return False

pytestmark = pytest.mark.skipif(
    not _db_has_tables(),
    reason="Performance tests require populated db/coverage.db (run ATT&CK ingest first)",
)


@pytest.fixture(scope="module")
def perf_engine():
    """Engine for perf tests (read-only-ish, no mutations committed)."""
    engine = make_engine(database_url())
    yield engine
    engine.dispose()


@pytest.fixture(scope="module")
def perf_config():
    return load_config("config.yaml")


def _full_recompute(session, config) -> float:
    """Run the full recompute path, return elapsed seconds."""
    start = time.perf_counter()
    rows = list(load_coverage_rows(session, config))
    tactic_cov = coverage_by_tactic(rows)
    rules = load_mappings("data/attack_mappings.csv")
    gaps = calculate_coverage_gaps(rows, rules, config)
    result = session.execute(select(SimulationResult)).scalars().first()
    if result:
        simulate_apt_attack(
            result.group_id, session=session, config=config, persist=False
        )
    elapsed = time.perf_counter() - start
    # Touch results so the compiler can't elide the work.
    _ = (len(rows), len(tactic_cov), len(gaps))
    return elapsed


def _cached_render_path(session, config) -> float:
    """Simulate a cached render: analysis already done, just aggregate.

    On the cached path the views have the pre-computed objects and only
    build the heatmap / cluster summaries. We approximate this by running
    the cheapest aggregation pipeline (load rows + by-tactic) twice and
    timing the second call (which hits any caching the views set up).
    """
    # First call: cold path.
    _ = list(load_coverage_rows(session, config))
    # Second call: cached path.
    start = time.perf_counter()
    rows = list(load_coverage_rows(session, config))
    _ = coverage_by_tactic(rows)
    elapsed = time.perf_counter() - start
    _ = len(rows)
    return elapsed


class TestPerformanceGates:
    def test_full_recompute_under_budget(
        self, perf_engine, perf_config
    ) -> None:
        Session = sessionmaker(bind=perf_engine)
        session = Session()
        try:
            elapsed = _full_recompute(session, perf_config)
        finally:
            session.close()
        assert elapsed < FULL_RECOMPUTE_BUDGET, (
            f"full recompute took {elapsed:.3f}s, exceeds {FULL_RECOMPUTE_BUDGET}s"
        )

    def test_cached_render_under_budget(
        self, perf_engine, perf_config
    ) -> None:
        Session = sessionmaker(bind=perf_engine)
        session = Session()
        try:
            elapsed = _cached_render_path(session, perf_config)
        finally:
            session.close()
        assert elapsed < CACHED_RENDER_BUDGET, (
            f"cached render took {elapsed:.3f}s, exceeds {CACHED_RENDER_BUDGET}s"
        )
